export function buildRolePermissions(role: UserRole): RolePermissions {
  const matrix = {} as RolePermissions;
  for (const mod of ALL_MODULES) {
    if (role === 'Super Admin') {
      matrix[mod] = { view: true, create: true, edit: true, approve: true, delete: true, export: true };
    } else if (mod === 'companies' || mod === 'super_admin') {
      matrix[mod] = { view: false, create: false, edit: false, approve: false, delete: false, export: false };
    } else if (role === 'Business Owner') {
      if (mod === 'audit_logs' || mod === 'settings') {
        matrix[mod] = { view: true, create: false, edit: false, approve: false, delete: false, export: true };
      } else {
        matrix[mod] = { view: true, create: true, edit: true, approve: true, delete: false, export: true };
      }
    } else if (role === 'Manager') {
      if (mod === 'accounting') {
        matrix[mod] = { view: false, create: false, edit: false, approve: false, delete: false, export: false };
      } else if (mod === 'audit_logs') {
        matrix[mod] = { view: true, create: false, edit: false, approve: false, delete: false, export: false };
      } else if (mod === 'settings') {
        matrix[mod] = { view: true, create: false, edit: false, approve: false, delete: false, export: false };
      } else {
        matrix[mod] = {
          view: true,
          create: true,
          edit: true,
          approve: true,
          delete: mod !== 'staff_management' && mod !== 'staff_list',
          export: true,
        };
      }
    } else if (role === 'Cashier') {
      const cashierAllowed: ModuleKey[] = ['dashboard', 'pos', 'customers', 'credit_sales', 'cash_management', 'payments'];
      if (cashierAllowed.includes(mod)) {
        matrix[mod] = {
          view: true,
          create: ['pos', 'customers', 'credit_sales', 'payments', 'cash_management'].includes(mod),
          edit: mod === 'pos',
          approve: false,
          delete: mod === 'pos',
          export: false,
        };
      } else if (mod === 'products') {
        matrix[mod] = { view: true, create: false, edit: false, approve: false, delete: false, export: false };
      } else {
        matrix[mod] = { view: false, create: false, edit: false, approve: false, delete: false, export: false };
      }
    } else {
      const stockAllowed: ModuleKey[] = ['dashboard', 'products', 'inventory', 'categories', 'purchasing', 'receiving', 'suppliers', 'reports'];
      if (stockAllowed.includes(mod)) {
        matrix[mod] = {
          view: true,
          create: ['products', 'inventory', 'categories', 'purchasing', 'receiving', 'suppliers'].includes(mod),
          edit: ['products', 'inventory', 'categories', 'purchasing', 'receiving', 'suppliers'].includes(mod),
          approve: mod === 'inventory' || mod === 'receiving',
          delete: ['products', 'inventory', 'categories', 'purchasing', 'receiving', 'suppliers'].includes(mod),
          export: ['products', 'inventory', 'purchasing', 'receiving', 'reports'].includes(mod),
        };
      } else {
        matrix[mod] = { view: false, create: false, edit: false, approve: false, delete: false, export: false };
      }
    }
  }
  return matrix;
}

