export function makeProductSvg(
  bg: string,
  accent: string,
  label: string,
  shape: 'bottle' | 'pack' | 'carton' | 'produce' | 'loaf' | 'eggs' | 'banana' = 'pack'
): string {
  let inner = '';
  if (shape === 'bottle') {
    inner = `
      <rect x="30" y="8" width="12" height="7" rx="2" fill="${accent}"/>
      <path d="M26 22 C26 17, 46 17, 46 22 L48 60 C48 63, 24 63, 24 60 Z" fill="${accent}" opacity="0.9"/>
      <rect x="25" y="33" width="22" height="15" rx="2" fill="#ffffff" opacity="0.95"/>
      <text x="36" y="44" font-family="Arial, sans-serif" font-size="7" font-weight="bold" fill="#0f172a" text-anchor="middle">${label}</text>
    `;
  } else if (shape === 'carton') {
    inner = `
      <polygon points="22,22 36,12 50,22" fill="${accent}" opacity="0.75"/>
      <rect x="22" y="22" width="28" height="40" rx="3" fill="${accent}"/>
      <rect x="25" y="31" width="22" height="18" rx="2" fill="#ffffff" opacity="0.95"/>
      <text x="36" y="43" font-family="Arial, sans-serif" font-size="7" font-weight="bold" fill="#0f172a" text-anchor="middle">${label}</text>
    `;
  } else if (shape === 'banana') {
    inner = `
      <path d="M18 48 C24 56, 44 56, 54 38 C56 34, 52 30, 48 34 C40 46, 26 44, 20 40 Z" fill="#eab308"/>
      <path d="M24 44 C28 50, 44 50, 52 36" stroke="#ca8a04" stroke-width="2" fill="none"/>
      <rect x="16" y="38" width="4" height="4" rx="1" fill="#713f12"/>
      <text x="36" y="26" font-family="Arial, sans-serif" font-size="7" font-weight="bold" fill="#0f172a" text-anchor="middle">${label}</text>
    `;
  } else if (shape === 'eggs') {
    inner = `
      <ellipse cx="28" cy="40" rx="9" ry="12" fill="#fed7aa"/>
      <ellipse cx="44" cy="40" rx="9" ry="12" fill="#fed7aa"/>
      <ellipse cx="36" cy="30" rx="8" ry="11" fill="#ffedd5"/>
      <text x="36" y="58" font-family="Arial, sans-serif" font-size="7" font-weight="bold" fill="#0f172a" text-anchor="middle">${label}</text>
    `;
  } else if (shape === 'loaf') {
    inner = `
      <path d="M16 36 C16 24, 56 24, 56 36 L54 56 C54 59, 18 59, 18 56 Z" fill="${accent}"/>
      <rect x="22" y="38" width="28" height="12" rx="2" fill="#ffffff" opacity="0.92"/>
      <text x="36" y="46" font-family="Arial, sans-serif" font-size="7" font-weight="bold" fill="#1e293b" text-anchor="middle">${label}</text>
    `;
  } else if (shape === 'produce') {
    inner = `
      <circle cx="32" cy="40" r="15" fill="${accent}"/>
      <circle cx="44" cy="44" r="12" fill="${accent}" opacity="0.85"/>
      <path d="M32 25 Q36 16 42 20" stroke="#15803d" stroke-width="3" fill="none" stroke-linecap="round"/>
      <text x="36" y="44" font-family="Arial, sans-serif" font-size="7" font-weight="bold" fill="#ffffff" text-anchor="middle">${label}</text>
    `;
  } else {
    inner = `
      <rect x="20" y="16" width="32" height="44" rx="4" fill="${accent}"/>
      <rect x="20" y="16" width="32" height="6" rx="2" fill="#000000" opacity="0.15"/>
      <rect x="24" y="28" width="24" height="18" rx="2" fill="#ffffff" opacity="0.94"/>
      <text x="36" y="40" font-family="Arial, sans-serif" font-size="7" font-weight="bold" fill="#0f172a" text-anchor="middle">${label}</text>
    `;
  }

  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 72 72" width="72" height="72">
    <rect width="72" height="72" rx="14" fill="${bg}"/>
    ${inner}
  </svg>`;
  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
}

